"""nl2opt：自然语言线性/整数规划 → 可运行、可验证、可迭代修复的求解模型与代码。

闭环：理解(Understand) → 建模(Model) → 生成(Generate) → 执行(Execute)
      → 验证(Verify) → 重写(Rewrite) → 回到对应环节。

默认采用“零新增依赖”方案：
- 求解器：已内置的 scipy.optimize（linprog / milp，底层 HiGHS）
- LLM 客户端：已内置的 httpx 直连 DeepSeek 的 OpenAI 兼容接口
"""

__version__ = "0.1.0"

# 评测协议版本：**任何会改变「同一输入 → 同一判定/行为」的改动都必须递增**。
# 例如：IR 可表达的模型范围、验证器的判据、重写的路由规则、Prompt 中影响
# LLM 输出形态的部分。仅重构、注释、报表脚本改动不需要递增。
#
# 为什么需要它：不同版本下的同一题，失败原因可能完全不同（例如某版本还不支持
# 某类索引、或尚未加入某项验证器检查）——两批结果**不可直接对比**，硬比会得出
# 错误结论。记录版本号后，对比工具可自动拒绝不可比批次。
#
# 版本历史（只记「改了什么」；具体实测细节见 git 历史）：
#   1 — 初版。
#   2 — IR 支持字符串索引与多维索引（index_set）。
#   3 — 验证器新增目标定义检查；目标值容差与可行性容差解耦（改为相对容差）。
#   4 — 验证器新增目标系数题面依据检查（后于 v30 移除，见该版本说明）。
#   5 — 提示词分层：常驻核心（1721 字符）+ 按题面命中的领域卡片。
#   6 — max_tokens 由 32768 提升到 65536：实测 32768 对最大排班实例是**临界值**。
#   7 — 卡片触发词「宁多勿漏」：离线审计发现 5 处真实漏检。
#   8 — 三项行为变更。
#   9 — 判定修订：`converged`（重写后达到参考值）**计为通过**，status 保留。
#   10 — 剥离「答案泄露」：check_optimality 的失败 message 不再含参考答案数值。
#   11 — 修复重复线性项导致的双后端语义分叉（P0）。
#   12 — 收紧 IR 数值与边界校验（P0）：契约错误在入口拒绝，而非推迟成执行错误。
#   13 — 变量名安全（P0）：IR 变量名与底层标识符解耦。
#   14 — 验证器拒绝「不完整/非有限」的解向量（P1）：可行性检查先做解向量完整性。
#   15 — 抽出统一 LLM 响应保护层（P1）：`llm.complete_structured(llm, messages, stage)`。
#   16 — 缓存键版本化与语义隔离（P1）：引入 `CacheContext`，缓存不再跨版本误复用。
#   17 — 目标系数依据检查改为「告警优先」分级（P2），避免启发式硬失败误伤。
#   18 — 新增目标值一致性检查（P0，闭合「执行→验证」可信边界）。
#   19 — 补全 CacheContext 的 prompt 指纹（P0.5），改变提示词策略即缓存失效。
#   20 — 提示词措辞纠偏（按危害排序，消除会诱导建模错误/幻觉的措辞）。
#   21 — 修正 v20 的 ② 措辞回归。
#   22 — ① 「不默认非负」的结构层修复（v20 的 ① 仅改措辞，实测**完全无效**）。
#   23 — 修复 suspicious 终止路径的「报告值与 final_ir 不一致」bug。
#   24 — fixed_cost 卡片补齐「两种固定成本」的语义区分（实测驱动）。
#   25 — IR 引用完整性保障（VRP / 网络流类变量族，实测驱动）。
#   26 — 固定支出必须落进 `objective.expr.constant`。
#   27 — 目标规划题的「答案不是目标函数值」。
#   28 — 参考答案人工核定（改正 + 标歧义）。
#   29 — 规则副作用修正（v28 全量跑暴露的 3 处回退，均非模型能力问题）。
#   30 — 移除 docker 后端与 L1 代码修复层：执行统一走进程内 scipy/HiGHS；
#        重写路由简化为单一策略（失败即 rewrite，最多 3 轮）。
#   31 — 思考强度固定 `low`（不再可调）：`medium` 在上千条约束的实例上会把
#        max_tokens 吃光，正文 JSON 被截断（finish_reason=length）。
#   32 — LLM 只产 SymbolicIR：删掉「LLM 直接产展平 IR」与展平层重写两条契约，
#        展平 IR 只由 `expand()` 产生（自由题面走空 DataStore 的同一链路）。
#   33 — 展开失败不再终止：`ExpandError` 与「求解/验证失败」合流，同样交 LLM 重写
#        （旧实现 rounds=0 直接返回，一次笔误即判死刑）。
#   34 — 缓存只留问题级（题面哈希 → SymbolicIR）：删掉 IR 级（省 5–500 ms 求解，
#        而 LLM 是 10–60 s）与代码级（代码生成早已移除）。
#   35 — 删掉缓存本身：它把「同一题多跑几次」塌缩成同一条轨迹（键就是题面），
#        而评测要的正是多次独立采样。同时删掉 `--no-cache`、`CacheContext`、
#        题面预处理（只为算缓存键而存在）。
#   36 — 每题多次「解答机会」（`pipeline.attempts`，默认 2）：一次机会 = 独立的理解
#        + 最多 2 次修复（`max_rounds: 3`），任一次成功即停；最后一次失败不再白花重写。
